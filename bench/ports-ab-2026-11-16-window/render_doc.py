#!/usr/bin/env python3
"""Render campaign 6 (batch verify-window width, the offset switches, and the CONF sweep).

Deltas are medians across every round an arm has, with per-round sign agreement beside them,
judged against this campaign's own A/A floor. The draft/verify telemetry comes from
telemetry.py (the batch line the engine prints when the slots go idle).
"""
import json, os, re, statistics as st

ROOT = '/home/soren/Strata-latest-20261112-182859/bench/ports-ab-2026-11-16-window'
DOC = '/home/soren/Strata-latest-20261112-182859/RDNA4-Ports.md'
BKEY = 'AB-CAMPAIGN-5'
BEGIN = f'<!-- {BKEY}:BEGIN -> generated by bench/ports-ab-2026-11-16-window/render_doc.py -->'
END = f'<!-- {BKEY}:END -->'
METRIC = {'warm': lambda r: r['greedy'][1]['wall_tok_s'],
          'burst': lambda r: r['burst']['aggregate_tok_s'],
          'p4k': lambda r: r['prefill']['wall_tok_s']}
NOTE = {
    'mt12_vs_prod': "window width alone: production's 8 rows against 12",
    'mt16_vs_prod': 'and against 16',
    'aa_floor': 'identical configs both sides - the floor every verdict is judged against',
    'fork_mt12': 'the fork at 12 rows (round 1 only)',
    'fork_mt16': 'the fork at 16 rows',
    'headil_mt12': 'IL head off at 12 rows (round 1 only)',
    'headil_mt16': 'IL head off at 16 rows',
    'chunk14_mt12': '14-row head chunk at 12 rows',
    'chunk14_mt16': '14-row head chunk at 16 rows (round 1 only)',
    'conf015_mt12': 'selector probability floor 0.35 -> 0.15 (drafts wider)',
    'conf025_mt12': '0.35 -> 0.25',
    'combo_fork_headil16': 'fork + IL head off at 16 rows',
    'combo_fork_headil_conf15_16': 'fork + IL head off + CONF 0.15 at 16 rows',
}


def rounds(prefix, sid):
    out = []
    if not os.path.isdir(f'{ROOT}/results'):
        return out
    for f in os.listdir(f'{ROOT}/results'):
        if re.fullmatch(re.escape(prefix + sid) + r'(_r\d+)?\.json', f) and not f.endswith('_long.json'):
            out.append(json.load(open(f'{ROOT}/results/{f}')))
    return sorted(out, key=lambda r: r.get('round') or 'r1')


def verdict(delta, signs, n, floor):
    if abs(delta) <= floor:
        return 'inside the floor (noise)'
    if signs < n:
        return f'**{delta:+.1f}%**, agrees {signs}/{n} rounds - not confirmed'
    return f'**{delta:+.1f}%**, agrees {signs}/{n} rounds'


def main():
    tab = json.load(open(f'{ROOT}/arms.json'))
    tele = {}
    tp = f'{ROOT}/results/telemetry.json'
    if os.path.exists(tp):
        tele = {r['arm']: r for r in json.load(open(tp))}
    floor = {'warm': 1.6, 'burst': 2.8, 'p4k': 0.4}   # this campaign's 3-round A/A medians
    rows, trows = [], []
    done = 0
    for a in tab['arms']:
        sid = a['id']
        c, t = rounds('ctl_', sid), rounds('trt_', sid)
        lbl = f'`{a.get("switch") or "binary"}` {a["baseline"] or "-"} -> {a["arm"] or "-"}'
        if not (c and t) or len(c) != len(t):
            rows.append(f'| {sid} | {lbl} | queued | - | - | - |')
            continue
        done += 1
        d = {}
        for k, fn in METRIC.items():
            cv, tv = st.median([fn(r) for r in c]), st.median([fn(r) for r in t])
            pr = [(fn(b) - fn(x)) / fn(x) * 100 for x, b in zip(c, t)]
            d[k] = ((tv - cv) / cv * 100, sum(1 for x in pr if (x > 0) == ((tv - cv) > 0) and abs(x) > 0.3))
        rows.append('| {} | {} | {} (n={}) | {} | {} | {} |'.format(
            sid, lbl, NOTE.get(sid, ''), len(c),
            verdict(d['warm'][0], d['warm'][1], len(c), floor['warm']),
            verdict(d['burst'][0], d['burst'][1], len(c), floor['burst']),
            verdict(d['p4k'][0], d['p4k'][1], len(c), floor['p4k'])))
        T = tele.get(sid)
        if T and T.get('ctl') and T.get('trt'):
            trows.append('| {} | {:.2f} -> {:.2f} | {:.1f} -> {:.1f} | {:+.1f} | {:.1f} -> {:.1f} |'.format(
                sid, T['ctl'].get('rows_per_window', 0), T['trt'].get('rows_per_window', 0),
                T['ctl'].get('accept_pct', 0), T['trt'].get('accept_pct', 0), T.get('accept_pct_delta', 0) or 0,
                T['ctl'].get('ms_per_window', 0), T['trt'].get('ms_per_window', 0)))

    body = '\n'.join([
        BEGIN, '',
        '## Batch verify-window width, its offset switches, and the CONF sweep - 2026-11-13',
        '',
        f'Progress: **{done}/{len(tab["arms"])}** arms measured. Build `fork-68872b2d1`, production profile and',
        'environment (`bench/ports-ab-2026-11-16-window/baseline-env.sh`, taken from the drop-in after the',
        '`STRATA_DF2_BEAM=4` correction). Production stayed stopped for the whole window.',
        '',
        '**Question.** `STRATA_BATCH_DF2_MAX_T` widens the batch verifier\'s draft window (production runs 8).',
        'Wider windows buy accepted tokens a round and cost per-window time; the hypothesis under test was that',
        '`STRATA_DF2_FORK=1`, `STRATA_DF2_HEAD_IL=0` and `STRATA_DF2_HEAD_CHUNK=14` absorb that cost at 12-16 rows,',
        'and that `STRATA_BATCH_DF2_CONF` (the selector-probability floor that ends a slot\'s draft rows) can be',
        'tuned to trade verify width against accepted tokens.',
        '',
        '**Floor.** The A/A pair (`MAX_T=12` on both sides, three rounds) moved **-1.6% solo, +2.8% burst, +0.4%**',
        'on the short-prompt workload, so the verdicts below are judged against +-1.6 / +-2.8 / +-0.4%.',
        '',
        '| arm | tested | note | warm solo | 2x256 burst | ~3.9k prompt reply |',
        '|---|---|---|---|---|---|',
    ] + rows + [
        '',
        '### Draft and verify telemetry',
        '',
        'From the batch line the engine prints when the slots go idle (one line a launch, not a median):',
        '',
        '| arm | rows/window (ctl -> arm) | accepted % (ctl -> arm) | d accepted | ms/window (ctl -> arm) |',
        '|---|---|---|---|---|',
    ] + trows + [
        '',
        '**These telemetry numbers are not a comparator.** Two identical configs (the A/A pair) differ by tens of',
        'points of acceptance, because the line describes whichever windows happened to be timed and which requests',
        'landed in them. They explain a wall-clock delta; they cannot stand in for one.',
        '',
        '### What the campaign says',
        '',
        '- **The window width is the only large, reproducible effect.** 8 -> 16 rows: **+11.4% solo decode**',
        '  (3/3 rounds) for **-7.6% concurrent burst** (3/3). 8 -> 12: +4.0% solo (2/3) for -7.0% burst (3/3), so 12',
        '  pays almost all of the burst cost for a third of the solo gain.',
        '- **None of the three offset switches held up.** `DF2_FORK=1` looked like +23.9% solo in the first round and',
        '  settled at +5.4% with 1/3 agreement; `DF2_HEAD_IL=0` looked like +10.7% burst in round 1 and finished at',
        '  **-5.3%** with 2/3 agreement; `DF2_HEAD_CHUNK=14` is inside the floor at both widths. The first-round',
        '  screen that motivated the combinations did not survive repetition - the failure mode the A/A floor rule',
        '  exists to catch.',
        '- **The CONF sweep does not recover it either.** `0.15` is +1.7% solo for -3.3% burst; `0.25` is -0.8% /',
        '  -1.9% (3/3). Production\'s 0.35 remains the best of the three tested.',
        '- **Stacking them makes it worse**: fork + IL-off + `CONF=0.15` at 16 rows is **-5.8% solo and -7.2% burst**,',
        '  agreeing 2/2 rounds.',
        '',
        '### Decision',
        '',
        '`STRATA_BATCH_DF2_MAX_T` stays at production\'s **8**, and no offset switch or CONF value is enabled: the',
        'server runs `parallel: 2`, where the burst is the workload users feel, and every arm that bought solo',
        'decode paid more in concurrent throughput than it gained. The knob is worth revisiting only for a',
        'single-stream deployment.',
        '',
        '### Reproduction',
        '',
        '```',
        'cd ~/Strata-latest-20261112-182859',
        'python3 bench/ports-ab-2026-11-16-window/gen_configs.py',
        'systemd-run --user --scope -- python3 bench/ports-ab-2026-11-16-window/driver.py --skip-ctest --no-restore',
        'systemd-run --user --scope -- python3 bench/ports-ab-2026-11-16-window/driver.py --skip-ctest --no-restore \\',
        '    --round-offset 1 --rounds 2 --only mt12_vs_prod,mt16_vs_prod,conf025_mt12',
        'python3 bench/ports-ab-2026-11-16-window/telemetry.py',
        'python3 bench/ports-ab-2026-11-16-window/render_doc.py',
        '```',
        '',
        END,
    ])
    doc = open(DOC).read()
    pat = re.compile(r'<!-- ' + BKEY + r':BEGIN.*?' + END + r' -->', re.S)
    doc = pat.sub(lambda _: body, doc) if pat.search(doc) else doc.rstrip() + '\n\n' + body + '\n'
    open(DOC, 'w').write(doc)
    print(f'rendered {done}/{len(tab["arms"])} arms, {len(trows)} telemetry rows')


if __name__ == '__main__':
    main()
