#!/usr/bin/env python3
"""Render the 2026-11-13 long-context campaign into RDNA4-Ports.md.

Two tables: the standard short-prompt workload (same metrics as the earlier campaigns) and the
64k / 128k context trials (prompt processing tok/s, TTFT, decode at depth). Deltas are medians
across rounds.
"""
import json, os, re, statistics as st

ROOT = '/home/soren/Strata-latest-20261112-182859/bench/ports-ab-2026-11-15-ctx'
DOC = '/home/soren/Strata-latest-20261112-182859/RDNA4-Ports.md'
BEGIN = '<!-- AB-CAMPAIGN-4:BEGIN -> generated by bench/ports-ab-2026-11-15-ctx/render_doc.py -->'
END = '<!-- AB-CAMPAIGN-4:END -->'
FLOOR = {'warm': 1.5, 'burst': 2.0, 'prefill': 1.4}   # 3-round A/A floor of the DFlash2 campaign


def rounds(prefix, sid, long=False):
    out = []
    if not os.path.isdir(f'{ROOT}/results'):
        return out
    for f in os.listdir(f'{ROOT}/results'):
        pat = re.escape(prefix + sid) + (r'(_r\d+)?_long\.json' if long else r'(_r\d+)?\.json')
        if re.fullmatch(pat, f) and (long or not f.endswith('_long.json')):
            out.append(json.load(open(f'{ROOT}/results/{f}')))
    return sorted(out, key=lambda r: r.get('round') or 'r1')


def pct(a, b):
    return None if (a is None or b in (None, 0)) else (a - b) / b * 100.0


def fmt(x, nd=1):
    return 'n/a' if x is None else f'{x:.{nd}f}'


def std_table(tab):
    rows = []
    for i, a in enumerate(tab['arms'], 1):
        sid = a['id']
        c, t = rounds('ctl_', sid), rounds('trt_', sid)
        label = '`%s` %s → %s' % (a.get('switch') or 'binary', a['baseline'] or '(unset)', a['arm'] or '(unset)')
        if not (c and t):
            rows.append(f'| {i} | {a["id"]} | {label} | queued | — | — | — |')
            continue
        f = lambda rs, k: st.median([r[k] for r in rs])
        cw, tw = f([{'w': r['greedy'][1]['wall_tok_s']} for r in c], 'w'), f([{'w': r['greedy'][1]['wall_tok_s']} for r in t], 'w')
        cb, tb = st.median([r['burst']['aggregate_tok_s'] for r in c]), st.median([r['burst']['aggregate_tok_s'] for r in t])
        cp, tp = st.median([r['prefill']['wall_tok_s'] for r in c]), st.median([r['prefill']['wall_tok_s'] for r in t])
        rows.append('| {} | {} | {} | {} (n={}) | {} → {} ({:+.1f}%) | {} → {} ({:+.1f}%) | {} → {} ({:+.1f}%) |'.format(
            i, a['id'], label, fmt(cw), len(c), fmt(cw), fmt(tw), pct(tw, cw),
            fmt(cb), fmt(tb), pct(tb, cb), fmt(cp), fmt(tp), pct(tp, cp)))
    return rows


def long_table(tab):
    rows = []
    for a in tab['arms']:
        if not a.get('long'):
            continue
        sid = a['id']
        c, t = rounds('ctl_', sid, long=True), rounds('trt_', sid, long=True)
        for label in ('64k', '128k'):
            ce = [x for r in c for x in r['contexts'] if x['label'] == label]
            te = [x for r in t for x in r['contexts'] if x['label'] == label]
            if not (ce and te):
                rows.append(f'| {sid} | {label} | queued | — | — | — | — |')
                continue
            cp = st.median([x['prompt_tokens_per_s'] for x in ce])
            tp = st.median([x['prompt_tokens_per_s'] for x in te])
            ct = st.median([x['prompt_wall_s'] for x in ce])
            tt = st.median([x['prompt_wall_s'] for x in te])
            dec = [x['decode_tok_s'] for x in te if (x['decode64'].get('completion_tokens') or 0) >= 32]
            cdec = [x['decode_tok_s'] for x in ce if (x['decode64'].get('completion_tokens') or 0) >= 32]
            d = 'n/a'
            if dec and cdec:
                d = f'{st.median(cdec):.1f} → {st.median(dec):.1f} ({pct(st.median(dec), st.median(cdec)):+.1f}%)'
            rows.append('| {} | {} | {} tok | {} → {} ({:+.1f}%) | {} → {} ({:+.1f}%) | {} | n={} |'.format(
                sid, label, f'{int(st.median([x["prompt_tokens"] for x in te])):,}',
                fmt(cp, 0), fmt(tp, 0), pct(tp, cp), fmt(ct), fmt(tt), pct(tt, ct), d, len(te)))
    return rows


def main():
    tab = json.load(open(f'{ROOT}/arms.json'))
    st_rows, lg_rows = std_table(tab), long_table(tab)
