#!/usr/bin/env python3
"""Rewrite the generated results section of RDNA4-Ports.md from results/*.json.

Every switch has one or more A/B rounds: round 1 is the screen sample (results/ctl_<id>.json /
trt_<id>.json), later rounds carry a _rN suffix. The A/A pairs (identical configuration launched
twice) define the launch-to-launch noise floor, and every verdict is judged against that floor
instead of a fixed percentage.
"""
import json, os, re
import statistics as st

ROOT = '/home/soren/Strata-latest-20261112-182859/bench/ports-ab-2026-11-12'
DOC = '/home/soren/Strata-latest-20261112-182859/RDNA4-Ports.md'
BEGIN = '<!-- AB-CAMPAIGN:BEGIN -> generated by bench/ports-ab-2026-11-12/render_doc.py; results are appended after each switch pair -->'
END = '<!-- AB-CAMPAIGN:END -->'
METRICS = ('warm', 'burst', 'prefill')


def rounds_of(prefix, sid):
    out = []
    if not os.path.isdir(f'{ROOT}/results'):
        return out
    for f in os.listdir(f'{ROOT}/results'):
        if re.fullmatch(re.escape(prefix + sid) + r'(_r\d+)?\.json', f):
            out.append(json.load(open(f'{ROOT}/results/{f}')))
    return sorted(out, key=lambda r: r.get('round') or 'r1')


def metrics(recs):
    if not recs:
        return None
    n = len(recs)
    slots = set()
    engw = []
    for r in recs:
        s = r.get('expert_cache')
        s = s[0] if isinstance(s, list) and s else s
        s = s if isinstance(s, str) else ''
        m = re.search(r'(\d+) slots', s)
        if m:
            slots.add(m.group(1))
        e = r.get('engine_decode_512') or []
        if len(e) > 1:
            engw.append(float(e[1]))
    return {
        'warm': sum(r['greedy'][1]['wall_tok_s'] for r in recs) / n,
        'cold': sum(r['greedy'][0]['wall_tok_s'] for r in recs) / n,
        'burst': sum(r['burst']['aggregate_tok_s'] for r in recs) / n,
        'prefill': sum(r['prefill']['wall_tok_s'] for r in recs) / n,
        'engine_warm': (sum(engw) / len(engw)) if engw else None,
        'slots': '/'.join(sorted(slots)) if slots else '?',
        'n': n,
        'bits': [r['parity']['greedy_cold'] for r in recs],
        'warm_med': st.median([r['greedy'][1]['wall_tok_s'] for r in recs]),
        'burst_med': st.median([r['burst']['aggregate_tok_s'] for r in recs]),
        'prefill_med': st.median([r['prefill']['wall_tok_s'] for r in recs]),
        'warm_rounds': [r['greedy'][1]['wall_tok_s'] for r in recs],
        'burst_rounds': [r['burst']['aggregate_tok_s'] for r in recs],
        'prefill_rounds': [r['prefill']['wall_tok_s'] for r in recs],
    }


def pct(a, b):
    return None if (a is None or b in (None, 0)) else (a - b) / b * 100.0


def fmt(x, nd=1):
    return 'n/a' if x is None else f'{x:.{nd}f}'


def floor_of(tab):
    fl = {m: 0.0 for m in METRICS}
    used = []
    for a in tab['arms']:
        if not a['id'].startswith('aa_floor'):
            continue
        c, t = metrics(rounds_of('ctl_', a['id'])), metrics(rounds_of('trt_', a['id']))
        if not (c and t):
            continue
        used.append(a['id'])
        for m in METRICS:
            d = pct(t[m], c[m])
            if d is not None:
                fl[m] = max(fl[m], abs(d))
    fl['burst'] = max(fl['burst'], 2.0)   # materiality floor: the A/A estimate rests on two pairs
    return fl, used


def consistency(cm, tm):
    """Per-round A/B deltas (control and treatment of a round ran back to back) and how many of them
    share the mean's sign — the cheap way to say 'small but repeatable' or 'noise'."""
    out = {}
    for m in METRICS:
        c, t = cm[m + '_rounds'], tm[m + '_rounds']
        ds = [pct(b, a) for a, b in zip(c, t)]
        ds = [d for d in ds if d is not None]
        if not ds:
            out[m] = (0, 0)
            continue
        mean = sum(ds) / len(ds)
        agree = sum(1 for d in ds if (d > 0) == (mean > 0))
        out[m] = (agree, len(ds))
    return out


def verdict(dw, db, dp, floor):
    """One clear sentence, judged against the measured A/A floor."""
    worse = [name for name, d, m in (('solo', dw, 'warm'), ('burst', db, 'burst'), ('prefill', dp, 'prefill'))
             if d is not None and d < -floor[m]]
    decode_fast = (dw is not None and dw > floor['warm']) and (db is not None and db > floor['burst'])
    if decode_fast and not worse:
        return '**faster than the production value** on solo and concurrent decode beyond the floor'
    if worse:
        return 'slower than the production value beyond the floor on: ' + ', '.join(worse)
    if dw is not None and dw > floor['warm']:
        return 'solo faster than the floor, concurrent decode flat — directional'
    return 'not separable from launch-to-launch noise'


def build():
    tab = json.load(open(f'{ROOT}/arms.json'))
    floor, floor_ids = floor_of(tab)
    rows, meta = [], []
    for i, a in enumerate(tab['arms'], 1):
        aa = a['id'].startswith('aa_floor')
        label = 'A/A floor (identical config)' if aa else '`%s`' % a['switch']
        cm, tm = metrics(rounds_of('ctl_', a['id'])), metrics(rounds_of('trt_', a['id']))
        if not cm:
            rows.append(f'| {i} | {label} | {a["baseline"]} | {a["arm"]} | queued | — | — | — | — | — | — |')
            continue
        if not tm:
            rows.append(f'| {i} | {label} | {a["baseline"]} | {a["arm"]} | {fmt(cm["warm"])} (n={cm["n"]}) | control only | pending | pending | pending | — | — | treatment not finished |')
            continue
        # medians across rounds, so one degraded launch cannot carry a verdict
        dw, db, dp = pct(tm['warm_med'], cm['warm_med']), pct(tm['burst_med'], cm['burst_med']), pct(tm['prefill_med'], cm['prefill_med'])
        degraded = []
        for side, mm in (('control', cm), ('treatment', tm)):
            ref = mm['warm_med']
            for k, v in enumerate(mm['warm_rounds'], 1):
                if ref > 0 and v < 0.85 * ref:
                    degraded.append(f'{side} round {k}: {v:.1f} tok/s vs {ref:.1f} median')
        dc = pct(tm['cold'], cm['cold'])
        if aa:
            bits = 'n/a (identical config)'
        elif set(cm['bits']) == set(tm['bits']):
            bits = 'same'
        elif a['bits'] == 'same':
            bits = 'differ (identical launches differ too — see floor)'
        else:
            bits = 'differ (expected: rounding-sensitive switch)'
        if aa:
            v = 'A/A floor sample (no treatment)'
        else:
            v = verdict(dw, db, dp, floor)
            notes = []
            cons = consistency(cm, tm)
            aw, nw = cons['warm']
            ab_, nb = cons['burst']
            if nw > 1:
                notes.append(f'round agreement solo {aw}/{nw}, burst {ab_}/{nb}')
                if aw == nw and nw > 1 and dw is not None and abs(dw) >= 1.5:
                    notes.append('solo direction stable in every round, magnitude sub-floor')
            if degraded:
                notes.append('degraded launch excluded from the median: ' + '; '.join(degraded))
            if notes:
                v += ' (' + '; '.join(notes) + ')'
        rows.append('| {} | {} | {} | {} | {} (n={}) | {} → {} ({:+.1f}%) | {} → {} ({:+.1f}%) | {} → {} ({:+.1f}%) | {} → {} ({:+.1f}%) | {} | {} | {} |'.format(
            i, label, a['baseline'], a['arm'],
            fmt(cm['warm']), cm['n'],
            fmt(cm['warm_med']), fmt(tm['warm_med']), dw,
            fmt(cm['burst_med']), fmt(tm['burst_med']), db,
            fmt(cm['prefill_med']), fmt(tm['prefill_med']), dp,
            fmt(cm['cold']), fmt(tm['cold']), dc,
            f"{fmt(cm['engine_warm'])} → {fmt(tm['engine_warm'])}", bits, v))
        meta.append({'id': a['id'], 'dw': dw, 'db': db, 'dp': dp, 'rounds': (cm['n'], tm['n'])})
    nt_rows = [f"| `{n['switch']}` | {n['why']} |" for n in tab.get('not_testable', [])]
    return rows, nt_rows, meta, floor, floor_ids, tab


