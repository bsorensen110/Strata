#!/usr/bin/env python3
"""Render Campaign 7 (16-row verify-window mitigations + build-hip vs fork-68872b2d1) into RDNA4-Ports.md.

Uses marker AB-CAMPAIGN-6 so it never collides with AB-CAMPAIGN-5 in RDNA4-Ports.md.
Deltas are medians across rounds with per-round spreads and sign agreement, judged against
this campaign's own A/A floor (aa_floor_mt16).
"""
import json, os, re, statistics as st

ROOT = '/home/soren/Strata-latest-20261112-182859/bench/ports-ab-2026-11-17-win16'
DOC = '/home/soren/Strata-latest-20261112-182859/RDNA4-Ports.md'
BKEY = 'AB-CAMPAIGN-6'
BEGIN = f'<!-- {BKEY}:BEGIN -> generated by bench/ports-ab-2026-11-17-win16/render_doc.py -->'
END = f'<!-- {BKEY}:END -->'
METRIC = {'warm': lambda r: r['greedy'][1]['wall_tok_s'],
          'burst': lambda r: r['burst']['aggregate_tok_s'],
          'p4k': lambda r: r['prefill']['wall_tok_s']}
NOTE = {
    'aa_floor_mt16': 'identical MAX_T=16 configs on fork-68872b2d1 - noise floor',
    'expdec_rb_d20_mt16': 'EXPDEC RB=128 / DRB=256 / EXPDEC_D20=1 at MAX_T=16',
    'newbuild_mt16_vs_old16': 'build-hip vs fork-68872b2d1 at MAX_T=16',
    'newbuild_mt16_vs_prod8': 'build-hip MAX_T=16 vs fork-68872b2d1 prod MAX_T=8',
    'newbuild_mt12_vs_prod8': 'build-hip MAX_T=12 vs fork-68872b2d1 prod MAX_T=8',
    'newbuild_mt16_pcie8_vs_prod8': 'build-hip MAX_T=16 + 8 GiB partial-pin PCIe vs fork-68872b2d1 prod MAX_T=8',
    'newbuild_mt8_pcie24_vs_prod8': 'build-hip MAX_T=8 + 24 GiB partial-pin PCIe + --pcie-frac 0.35 vs fork-68872b2d1 prod MAX_T=8',
    'newbuild_mt12_pcie24_vs_prod8': 'build-hip MAX_T=12 + 24 GiB partial-pin PCIe + --pcie-frac 0.35 vs fork-68872b2d1 prod MAX_T=8',
    'newbuild_mt16_pcie24_vs_prod8': 'build-hip MAX_T=16 + 24 GiB partial-pin PCIe + --pcie-frac 0.35 vs fork-68872b2d1 prod MAX_T=8',
}


def round_num(r):
    m = re.search(r'(\d+)$', str(r.get('round') or 'r1'))
    return int(m.group(1)) if m else 1


def rounds(prefix, sid):
    out = []
    if not os.path.isdir(f'{ROOT}/results'):
        return out
    for f in os.listdir(f'{ROOT}/results'):
        if re.fullmatch(re.escape(prefix + sid) + r'(_r\d+)?\.json', f) and not f.endswith('_long.json'):
            out.append(json.load(open(f'{ROOT}/results/{f}')))
    return sorted(out, key=round_num)


def paired_rounds(sid):
    cm = {round_num(r): r for r in rounds('ctl_', sid)}
    tm = {round_num(r): r for r in rounds('trt_', sid)}
    keys = sorted(set(cm) & set(tm))
    return [(rn, cm[rn], tm[rn]) for rn in keys]


def describe_arm(a):
    ce = a.get('ctl_exe') or a.get('exe_ctl')
    te = a.get('trt_exe') or a.get('exe_arm')
    ce_env = {str(k): str(v) for k, v in (a.get('ctl_env') or {}).items()}
    te_env = {str(k): str(v) for k, v in (a.get('trt_env') or {}).items()}
    parts = []
    if ce and te and ce != te:
        parts.append(f'`{os.path.basename(os.path.dirname(ce))}` -> `{os.path.basename(os.path.dirname(te))}`')
    if a.get('switch'):
        parts.append(f'`{a["switch"]}` {a.get("baseline") or "-"} -> {a.get("arm") or "-"}')
    elif ce_env or te_env:
        diffs = []
        for k in sorted(set(ce_env) | set(te_env)):
            if ce_env.get(k) != te_env.get(k):
                short_k = k.removeprefix('STRATA_')
                diffs.append(f'`{short_k}` {ce_env.get(k, "off")}->{te_env.get(k, "off")}')
        if diffs:
            parts.append(', '.join(diffs))
        else:
            same = [f'`{k.removeprefix("STRATA_")}={v}`' for k, v in sorted(te_env.items())]
            parts.append(', '.join(same) or 'identical')
    for role_lbl, key in (('ctl', 'args_ctl'), ('trt', 'args_arm')):
        extra = [str(x) for x in (a.get(key) or [])]
        if extra:
            tag = '' if key == 'args_arm' and not a.get('args_ctl') else f'{role_lbl} '
            parts.append(f'{tag}`{" ".join(extra)}`')
    return ' + '.join(parts) or a['id']


def measure_floor(arms):
    floor = {}
    aa_notes = []
    for a in arms:
        if not a['id'].startswith('aa_floor'):
            continue
        pairs = paired_rounds(a['id'])
        if not pairs:
            continue
        c = [x for _, x, _ in pairs]
        t = [y for _, _, y in pairs]
        vals = {}
        for k, fn in METRIC.items():
            cv, tv = st.median([fn(r) for r in c]), st.median([fn(r) for r in t])
            d = (tv - cv) / cv * 100
            vals[k] = d
            floor[k] = max(floor.get(k, 0.0), abs(d))
        aa_notes.append(
            f'`{a["id"]}` (n={len(pairs)}): {vals["warm"]:+.1f}% solo, {vals["burst"]:+.1f}% burst, {vals["p4k"]:+.1f}% p4k'
        )
    return floor, aa_notes


def verdict(delta, signs, n, floor_val):
    if floor_val is not None and abs(delta) <= floor_val:
        return 'inside the floor (noise)'
    if signs < n:
        return f'**{delta:+.1f}%**, agrees {signs}/{n} rounds - not confirmed'
    return f'**{delta:+.1f}%**, agrees {signs}/{n} rounds'


def fmt_spread(per_round):
    if not per_round:
        return '-'
    vals = [f'r{rn}:{v:+.1f}%' for rn, v in per_round]
    nums = [v for _, v in per_round]
    span = max(nums) - min(nums) if len(nums) > 1 else 0.0
    return f"{', '.join(vals)} (span {span:.1f}pp)"


def fmt_split(node):
    if not node or node.get('bt_run') is None:
        return '-'
    return f"{node['bt_run']:.1f}/{node.get('gpu_wait', 0):.1f}/{node.get('cpu_exp', 0):.1f}/{node.get('other_ms', 0):.2f}"


def main():
    tab = json.load(open(f'{ROOT}/arms.json'))
    arms = tab['arms']
    tele = {}
    tp = f'{ROOT}/results/telemetry.json'
    if os.path.exists(tp):
        tele = {r['arm']: r for r in json.load(open(tp))}
    floor, aa_notes = measure_floor(arms)
    rows, srows, trows = [], [], []
    done = 0
    for a in arms:
        sid = a['id']
        grp = a.get('group', '-')
        pairs = paired_rounds(sid)
        lbl = describe_arm(a)
        if not pairs:
            rows.append(f'| {grp} | {sid} | {lbl} | {NOTE.get(sid, a.get("why", ""))} | queued | - | - |')
            continue
        done += 1
        c = [x for _, x, _ in pairs]
        t = [y for _, _, y in pairs]
        d = {}
        pr_map = {}
        for k, fn in METRIC.items():
            cv, tv = st.median([fn(r) for r in c]), st.median([fn(r) for r in t])
            pr = [(rn, (fn(b) - fn(x)) / fn(x) * 100) for rn, x, b in pairs]
            pr_map[k] = pr
            med_d = (tv - cv) / cv * 100
            d[k] = (med_d, sum(1 for _, x in pr if (x > 0) == ((tv - cv) > 0) and abs(x) > 0.3))
        rows.append('| {} | {} | {} | {} (n={}) | {} | {} | {} |'.format(
            grp, sid, lbl, NOTE.get(sid, a.get('why', '')), len(pairs),
            verdict(d['warm'][0], d['warm'][1], len(pairs), floor.get('warm')),
            verdict(d['burst'][0], d['burst'][1], len(pairs), floor.get('burst')),
            verdict(d['p4k'][0], d['p4k'][1], len(pairs), floor.get('p4k'))))

        warm_eq = sum(1 for _, x, y in pairs if x.get('parity', {}).get('greedy_warm') == y.get('parity', {}).get('greedy_warm'))
        cold_eq = sum(1 for _, x, y in pairs if x.get('parity', {}).get('greedy_cold') == y.get('parity', {}).get('greedy_cold'))
        burst_eq = sum(
            1 for _, x, y in pairs
            if x.get('parity', {}).get('burst_a') == y.get('parity', {}).get('burst_a')
            and x.get('parity', {}).get('burst_b') == y.get('parity', {}).get('burst_b')
        )
        srows.append('| {} | {} | {} | {} | warm {}/{}, cold {}/{}, burst {}/{} |'.format(
            sid, fmt_spread(pr_map['warm']), fmt_spread(pr_map['burst']), fmt_spread(pr_map['p4k']),
            warm_eq, len(pairs), cold_eq, len(pairs), burst_eq, len(pairs),
        ))

        T = tele.get(sid)
        if T and T.get('ctl') and T.get('trt'):
            tc, tt = T['ctl'], T['trt']
            trows.append('| {} | {:.2f} -> {:.2f} | {:.1f} -> {:.1f} | {:+.1f} | {:.1f} -> {:.1f} | {} -> {} | {}/{} ({}/{}) |'.format(
                sid, tc.get('rows_per_window', 0), tt.get('rows_per_window', 0),
                tc.get('accept_pct', 0), tt.get('accept_pct', 0), T.get('accept_pct_delta', 0) or 0,
                tc.get('ms_per_window', 0), tt.get('ms_per_window', 0),
                fmt_split(tc), fmt_split(tt),
                tc.get('gpu_pause_count', 0), tt.get('gpu_pause_count', 0),
                tc.get('gpu_pause_ms', 0), tt.get('gpu_pause_ms', 0),
            ))

    floor_line = (
        '**Floor.** ' + '; '.join(aa_notes) +
        f' -> threshold +-{(floor.get("warm") or 0):.1f} / +-{(floor.get("burst") or 0):.1f} / +-{(floor.get("p4k") or 0):.1f}%.'
        if aa_notes else
        '**Floor.** Pending `aa_floor_mt16` measurement; raw deltas shown until the A/A floor is recorded.'
    )

    body = '\n'.join([
        BEGIN, '',
        '## Campaign 7: 16-row verify-window mitigations and build-hip vs fork-68872b2d1 - 2026-11-17',
        '',
        f'Progress: **{done}/{len(arms)}** arms measured. Group A tests zero-code env switches on',
        '`fork-68872b2d1`; Group B tests `build-hip/strata` (WS1-WS7) against `fork-68872b2d1` across',
        '12/16-row verify windows and `MAX_T=8` production.',
        '',
        floor_line,
        '',
        '| group | arm | tested | note | warm solo | 2x256 burst | ~3.9k prompt reply |',
        '|---|---|---|---|---|---|---|',
    ] + rows + [
        '',
        '### Per-round spreads and parity',
        '',
        '| arm | warm solo rounds | 2x256 burst rounds | ~3.9k prompt reply rounds | bit-identical parity |',
        '|---|---|---|---|---|',
    ] + (srows if srows else ['| (pending) | - | - | - | - |']) + [
        '',
        '### Draft and verify telemetry',
        '',
        'Median across available round logs (`bt_run/gpu_wait/cpu_exp/other` are `ms/window` components, `other = bt_run - (gpu_wait + cpu_exp)`):',
        '',
        '| arm | rows/window (ctl -> arm) | accepted % (ctl -> arm) | d accepted | ms/window (ctl -> arm) | bt_run/gpu_wait/cpu_exp/other (ctl -> arm) | GPU pauses ctl/trt (ms) |',
        '|---|---|---|---|---|---|---|',
    ] + (trows if trows else ['| (pending) | - | - | - | - | - | - |']) + [
        '',
        '### Reproduction',
        '',
        '```',
        'cd ~/Strata-latest-20261112-182859',
        'python3 bench/ports-ab-2026-11-17-win16/gen_configs.py',
        'systemd-run --user --scope -- python3 bench/ports-ab-2026-11-17-win16/driver.py --rounds 3 --skip-ctest --no-restore',
        'python3 bench/ports-ab-2026-11-17-win16/telemetry.py',
        'python3 bench/ports-ab-2026-11-17-win16/render_doc.py',
        '```',
        '',
        END,
    ])
    doc = open(DOC).read()
    pat = re.compile(r'<!-- ' + re.escape(BKEY) + r':BEGIN\b.*?' + re.escape(END), re.S)
    doc = pat.sub(lambda _: body, doc) if pat.search(doc) else doc.rstrip() + '\n\n' + body + '\n'
    open(DOC, 'w').write(doc)
    print(f'rendered {done}/{len(arms)} arms, {len(trows)} telemetry rows')


if __name__ == '__main__':
    main()
