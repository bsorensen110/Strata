#!/usr/bin/env python3
"""Render the 2026-11-13 new-optimization campaign into RDNA4-Ports.md.

Two tables: the engine-binary delta (production engine vs the new fork-main build, identical argv and
environment) and the new switches that the delta exposes. Deltas are medians across rounds, judged
against A/A floor pairs measured in the same window. Rewritten after every arm.
"""
import json, os, re, statistics as st

ROOT = '/home/soren/Strata-latest-20261112-182859/bench/ports-ab-2026-11-13-env'
DOC = '/home/soren/Strata-latest-20261112-182859/RDNA4-Ports.md'
BEGIN = '<!-- AB-CAMPAIGN-3:BEGIN -> generated by bench/ports-ab-2026-11-13-env/render_doc.py -->'
END = '<!-- AB-CAMPAIGN-3:END -->'
METRICS = ('warm', 'burst', 'prefill')


def rounds_of(prefix, sid):
    out = []
    if not os.path.isdir(f'{ROOT}/results'):
        return out
    for f in os.listdir(f'{ROOT}/results'):
        if re.fullmatch(re.escape(prefix + sid) + r'(_r\d+)?\.json', f):
            out.append(json.load(open(f'{ROOT}/results/{f}')))
    return sorted(out, key=lambda r: r.get('round') or 'r1')


def metrics(recs):
    if not recs:
        return None
    slots, engw = set(), []
    for r in recs:
        s = r.get('expert_cache')
        s = s[0] if isinstance(s, list) and s else s
        s = s if isinstance(s, str) else ''
        m = re.search(r'(\d+) slots', s)
        if m:
            slots.add(m.group(1))
        e = r.get('engine_decode_512') or []
        if len(e) > 1:
            engw.append(float(e[1]))
    return {
        'warm': sum(r['greedy'][1]['wall_tok_s'] for r in recs) / len(recs),
        'cold': sum(r['greedy'][0]['wall_tok_s'] for r in recs) / len(recs),
        'burst': sum(r['burst']['aggregate_tok_s'] for r in recs) / len(recs),
        'prefill': sum(r['prefill']['wall_tok_s'] for r in recs) / len(recs),
        'warm_med': st.median([r['greedy'][1]['wall_tok_s'] for r in recs]),
        'burst_med': st.median([r['burst']['aggregate_tok_s'] for r in recs]),
        'prefill_med': st.median([r['prefill']['wall_tok_s'] for r in recs]),
        'warm_rounds': [r['greedy'][1]['wall_tok_s'] for r in recs],
        'burst_rounds': [r['burst']['aggregate_tok_s'] for r in recs],
        'prefill_rounds': [r['prefill']['wall_tok_s'] for r in recs],
        'engine_warm': (sum(engw) / len(engw)) if engw else None,
        'slots': '/'.join(sorted(slots)) if slots else '?',
        'n': len(recs),
        'bits': [r['parity']['greedy_cold'] for r in recs],
        'exe': recs[0].get('exe', ''),
        'sha': recs[0].get('binary_sha256', ''),
        'mem': recs[0].get('resident_ram', ''),
    }


def pct(a, b):
    return None if (a is None or b in (None, 0)) else (a - b) / b * 100.0


def fmt(x, nd=1):
    return 'n/a' if x is None else f'{x:.{nd}f}'


def floor_of(tab):
    fl = {m: 0.0 for m in METRICS}
    used = []
    for a in tab['arms']:
        if not a['id'].startswith('aa_floor'):
            continue
        c, t = metrics(rounds_of('ctl_', a['id'])), metrics(rounds_of('trt_', a['id']))
        if not (c and t):
            continue
        used.append(a['id'])
        for m in METRICS:
            # same statistic as the rows (medians), so the floor and the deltas are comparable
            d = pct(t[m + '_med'], c[m + '_med'])
            if d is not None:
                fl[m] = max(fl[m], abs(d))
    fl['burst'] = max(fl['burst'], 2.0)
    return fl, used


def consistency(cm, tm):
    out = {}
    for m in METRICS:
        ds = [p for p in (pct(b, a) for a, b in zip(cm[m + '_rounds'], tm[m + '_rounds'])) if p is not None]
        if not ds:
            out[m] = (0, 0)
            continue
        mean = sum(ds) / len(ds)
        out[m] = (sum(1 for d in ds if (d > 0) == (mean > 0)), len(ds))
    return out


def degraded(cm, tm):
    out = []
    for side, mm in (('control', cm), ('treatment', tm)):
        ref = mm['warm_med']
        for k, v in enumerate(mm['warm_rounds'], 1):
            if ref > 0 and v < 0.85 * ref:
                out.append(f'{side} round {k}: {v:.1f} vs {ref:.1f} median')
    return out


def verdict(dw, db, dp, floor):
    worse = [n for n, d, m in (('solo', dw, 'warm'), ('burst', db, 'burst'), ('prefill', dp, 'prefill'))
             if d is not None and d < -floor[m]]
    decode_fast = (dw is not None and dw > floor['warm']) and (db is not None and db > floor['burst'])
    if decode_fast and not worse:
        return '**faster than the control** on solo and concurrent decode beyond the floor'
    if worse:
        return 'slower than the control beyond the floor on: ' + ', '.join(worse)
    if dw is not None and dw > floor['warm']:
        return 'solo faster than the floor, concurrent decode flat — directional'
    if not worse and all(d is not None and d > 0 for d in (dw, db, dp)):
        return 'faster on all three workloads by median, magnitude at or inside the floor'
    return 'not separable from launch-to-launch noise'


def short(exe):
    parts = exe.rstrip('/').split('/')
    return parts[-2] if len(parts) > 1 else parts[-1]


def build():
    tab = json.load(open(f'{ROOT}/arms.json'))
    floor, floor_ids = floor_of(tab)
    bin_rows, sw_rows, done, pending = [], [], 0, []
    for i, a in enumerate(tab['arms'], 1):
        sid = a['id']
        cm, tm = metrics(rounds_of('ctl_', sid)), metrics(rounds_of('trt_', sid))
        is_bin = not a.get('switch')
        aa = sid.startswith('aa_floor')
        label = 'A/A floor (identical config)' if aa else ('engine binary' if is_bin else '`%s`' % a['switch'])
        base_col = a['baseline'] if a['baseline'] != '' else '(unset/auto)'
        if not cm:
            (bin_rows if is_bin else sw_rows).append(
                f'| {i} | {label} | {base_col} | {a["arm"]} | queued | — | — | — | — | — |')
            pending.append(sid)
            continue
        if not tm:
            (bin_rows if is_bin else sw_rows).append(
                f'| {i} | {label} | {base_col} | {a["arm"]} | {fmt(cm["warm_med"])} (n={cm["n"]}) | control only '
                '| pending | pending | pending | treatment not finished |')
            pending.append(sid)
            continue
        done += 1
        dw, db, dp = (pct(tm['warm_med'], cm['warm_med']), pct(tm['burst_med'], cm['burst_med']),
                      pct(tm['prefill_med'], cm['prefill_med']))
        dc = pct(tm['cold'], cm['cold'])
        if aa:
            v = 'A/A floor sample (no treatment)'
        else:
            v = verdict(dw, db, dp, floor)
            notes = []
            cons = consistency(cm, tm)
            aw, nw = cons['warm']
            ab_, nb = cons['burst']
            if nw > 1:
                notes.append(f'round agreement solo {aw}/{nw}, burst {ab_}/{nb}')
            if (dg := degraded(cm, tm)):
                notes.append('degraded launch: ' + '; '.join(dg))
            if is_bin:
                notes.insert(0, f'`{short(cm["exe"])}` {cm["sha"][:12]} → `{short(tm["exe"])}` {tm["sha"][:12]}')
            if notes:
                v += ' (' + '; '.join(notes) + ')'
        if aa:
            bits = 'n/a (identical config)'
        elif set(cm['bits']) == set(tm['bits']):
            bits = 'same'
        else:
            bits = 'differ'
        row = '| {} | {} | {} | {} | {} (n={}) | {} → {} ({:+.1f}%) | {} → {} ({:+.1f}%) | {} → {} ({:+.1f}%) | {} → {} ({:+.1f}%) | {} |'.format(
            i, label, base_col, a['arm'], fmt(cm['warm_med']), cm['n'],
            fmt(cm['warm_med']), fmt(tm['warm_med']), dw,
            fmt(cm['burst_med']), fmt(tm['burst_med']), db,
            fmt(cm['prefill_med']), fmt(tm['prefill_med']), dp,
            fmt(cm['cold']), fmt(tm['cold']), dc,
            bits + ' · ' + v)
        (bin_rows if is_bin else sw_rows).append(row)
    return bin_rows, sw_rows, done, len(tab['arms']), pending, floor, floor_ids, tab


