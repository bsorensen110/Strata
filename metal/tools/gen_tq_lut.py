#!/usr/bin/env python3
"""Rewrites the tq_lut_u32 table in metal/kernels/quant.metal from third_party/ggml/ggml-common-tq.h.

The trellis codebook is 2048 points of two fp16 values; the kernels read a point as one 32-bit word (low half = first value).
Run from the repository root after the header changes:  python3 metal/tools/gen_tq_lut.py
"""
import re
import sys

HDR = "third_party/ggml/ggml-common-tq.h"
MSL = "metal/kernels/quant.metal"
BEGIN, END = "// TQ_LUT_BEGIN", "// TQ_LUT_END"


def main() -> int:
    h = open(HDR).read()
    m = re.search(r"tq_lut_f16\[4096\]\s*=\s*\{(.*?)\};", h, re.S)
    vals = [int(x, 16) for x in re.findall(r"0x[0-9a-fA-F]+", m.group(1))]
    if len(vals) != 4096:
        print("expected 4096 codebook halves, got", len(vals))
        return 1
    words = [vals[2 * i] | (vals[2 * i + 1] << 16) for i in range(2048)]
    rows = []
    for i in range(0, 2048, 8):
        rows.append("    " + ", ".join("0x%08xu" % w for w in words[i:i + 8]) + ",")
    body = BEGIN + " (generated by metal/tools/gen_tq_lut.py from " + HDR + ")\n" \
        + "constant uint tq_lut_u32[2048] = {\n" + "\n".join(rows) + "\n};\n" + END
    s = open(MSL).read()
    a, b = s.index(BEGIN), s.index(END) + len(END)
    open(MSL, "w").write(s[:a] + body + s[b:])
    return 0


if __name__ == "__main__":
    sys.exit(main())
